def club(bpm=118):
    """THE CLUBHOUSE, and the only track in the set whose job is to be IGNORED —
    it plays for minutes on end while somebody reads a team sheet.

    118 BPM, three above HeatleyBros' measured 115; the tempo was never the
    problem. What makes "8 Bit Joy" feel fast is that its lead never stops
    moving and its bass bounces root-octave underneath, so every slot here is
    written `busy` over a bouncing bass and the tune just runs.

    **What changed is the weight.** Menu and hosted were both written the same
    way — busy, bouncing, 50 % duty, full kit — and the three of them measured
    0.90+ against each other. Club is the one that should give ground, because
    constant motion and constant PROMINENCE are different things and only the
    first is in its job description. So: **25 % duty throughout**, where menu is
    50 %, and the sparsest kit in the set — kick, a snare on four, hats on the
    quarters, no fills at all. Thin and moving, which is what furniture music
    is. The dynamics still do not move; the volume does."""
    form = [
        Slot("A", duty=0.25, gain=0.175, busy_shape=(0, 1), bass_bounce=True, ficta_=True),
        Slot("A", duty=0.25, gain=0.175, busy_shape=(0, 1), bass_bounce=True,
             counter={"semis": -5, "gain": 0.05, "duty": 0.25}),
        Slot("B", duty=0.25, gain=0.175, busy_shape=(0, 2), bass_bounce=True),
        Slot("B", duty=0.25, gain=0.165, busy_shape=(0, 1), bass_bounce=True,
             counter={"semis": -12, "gain": 0.055}),
        Slot("A", duty=0.25, gain=0.175, oct_=-1, busy_shape=(0, -1), bass_bounce=True,
             counter={"semis": 12, "gain": 0.045}),
        Slot("B", duty=0.25, gain=0.175, busy_shape=(0, 1), bass_bounce=True,
             counter={"semis": -5, "gain": 0.06, "duty": 0.25}),
        Slot("A", duty=0.25, gain=0.185, busy_shape=(0, 2), bass_bounce=True,
             counter={"semis": 7, "gain": 0.05}),
        Slot("A", duty=0.25, gain=0.175, busy_shape=(0, 1), bass_bounce=True,
             bass_gain=0.24, ficta_=True),
    ]
    s = sized(bpm, form)
    lay_form(s, form)
