    for bar in range(int(s.beats // 4)):
        base = bar * 4
        s.kick(base, 0.30)
        s.kick(base + 2, 0.24)
        s.snare(base + 3, 0.15, period=2)
        for e in (0, 1, 2, 3):
            s.hat(base + e, 0.035)
    return s


