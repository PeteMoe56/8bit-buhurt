def ficta(phrase):
    """MUSICA FICTA — raise F to F# when the line steps up into G.

    Not an effect and not borrowed from anywhere: this is what singers actually
    did in the fourteenth century, and the reason it is written out here rather
    than into the mode is that it is a RULE ABOUT MOTION, not a scale degree.
    D Dorian has an F natural; a line ascending F->G sharpens it, because the
    half step pulls into the note it is heading for. Descending, it stays flat.

    Two consequences, both wanted. It is period-correct — the set's whole claim
    is a folk mode with a raised sixth, and ficta is the other half of that
    practice. And it puts a little major color in a minor set, at cadence
    points, which is what stops the front door and the clubhouse sounding like
    two different games.

    Only F->G, only ascending, only when the two are adjacent in time."""
    out = []
    for i, (b, note, ln) in enumerate(phrase):
        nxt = phrase[i + 1] if i + 1 < len(phrase) else None
        if (note is not None and nxt is not None and nxt[1] is not None
                and note[:-1] == "F" and nxt[1][:-1] == "G"
                and abs((b + ln) - nxt[0]) < 1e-6
                and hz(nxt[1]) > hz(note)):
            note = transpose(note, 1)
        out.append((b, note, ln))
    return out


def walk(line):
    """ROOT, FIFTH, OCTAVE, FIFTH — where `bounce()` gives root-octave-root.

    The difference matters more than it looks: a bounce is a pulse and a walk is
    a LINE, so the two read as different instruments playing different parts
    even under the same tune. `menu` walks and `club` bounces, and that is one
    of the three things now keeping them apart."""
    out = []
    for note in line:
        out += [note, transpose(note, 7), transpose(note, 12), transpose(note, 7)]
    return out


def major_lift(note):
    """DORIAN -> IONIAN.  F becomes F#, C becomes C#, and the tune you have been
    hearing all game arrives in the bright mode.  This is the oldest device in
    game music — the victory version of the theme — and it still works because
    the listener has earned the resolution over several hours."""
    if note is None:
        return None
    if note[0].upper() == "F" and "#" not in note:
        return "F#" + note[1:]
    if note[0].upper() == "C" and "#" not in note:
        return "C#" + note[1:]
    return note


def lay_melody(song, at, phrase, duty=0.5, gain=0.22, lift=False, chan="p1", vib=False):
    for (b, note, ln) in phrase:
        song.lead(at + b, major_lift(note) if lift else note, ln,
                  duty=duty, gain=gain, vib=vib, chan=chan)


def lay_bass(song, at, line, per=1.0, gain=0.30, lift=False):
    for i, note in enumerate(line):
        song.bass(at + i * per, major_lift(note) if lift else note, per, gain)




# ================================================================== THE FORM
# THE BUG THIS EXISTS TO STOP.
#
# A phrase is 16 beats — four bars. The first version of these arrangements laid
# PHRASE_A and PHRASE_B once each, eight bars in total, into a song declared as
# THIRTY-TWO bars. The remaining twenty-four bars had a full drum kit and no
# music whatsoever, on every track in the set.
#
# Pete heard it immediately: *"They all started off good, but tailed off hard
# with just the drums in the middle."* Measured afterwards at **75% of every
# loop**. Nothing caught it because nothing was looking — the renderer is happy
# to write silence and the mastering chain is happy to normalise it.
#
# So an arrangement is now a FORM: an explicit list of which phrase plays in
# each four-bar slot and how it is voiced. A song's length is derived from the
# form rather than declared next to it, which makes the two impossible to
# disagree, and `check_holes()` fails the build if any slot comes out empty.

## WHY 112 FELT SLOW WHEN IT WAS NOT.
##
## Pete: *"What BPM is Retro Bowl? it seems much faster than 112."* Measured:
## HeatleyBros' "8 Bit Joy" is **115 BPM in G major** — so the tempo was already
## within three beats of the reference and was never the problem.
##
## What makes that track feel fast is NOTE DENSITY. Its lead is in constant
## eighth-note motion and its bass bounces root-octave underneath; ours held
## notes for two whole beats and put a root on every bar. Same tempo, half the
## events, and the ear reads events rather than metronome marks. (The tempo
## services even list it as playable "double-time at 230" — which is the same
## observation from the other side: the sixteenth pulse is what you feel.)
##
## So the fix is writing, not tempo. `busy()` subdivides a held note into
## movement using the mode's own neighbors, which keeps the melody recognizable
## — it is still the same tune, it just never stops moving.
NEIGHBOR = ["D", "E", "F", "G", "A", "B", "C"]


def step_in_mode(note, steps):
    """Move up or down the D Dorian scale by degree, not by semitone — which is
    what keeps a passing note inside the mode and stops the medieval flavour
    leaking out through an accidental."""
    if note is None or steps == 0:
        return note
    name = note[0].upper()
    acc = "#" if "#" in note else ""
    octave = int(note[-1])
    ## THE OCTAVE BOUNDARY IS AT C, AND THE LIST STARTS AT D.
    ##
    ## Scientific pitch notation rolls the octave number over at C, not at the
    ## root of whatever mode you are in — so in a D-rooted list, C is the one
    ## degree that belongs to the octave ABOVE the D it sits with. Ignoring that
    ## put a passing note a full octave below where it belonged: D5 stepped down
    ## by one came out as C4 instead of C5, which is not a neighbor tone, it is
    ## a leap out of the phrase.
    i = NEIGHBOR.index(name) if name in NEIGHBOR else 0
    j = i + steps
    out = NEIGHBOR[j % len(NEIGHBOR)]
    octave += j // len(NEIGHBOR)
    if out == "C":
        octave += 1
    return out + acc + str(octave)


def busy(phrase, min_len=1.0, shape=(0, 1)):
    """Subdivide anything held for `min_len` or longer into eighths that walk
    the mode. `shape` is the degree offsets to cycle through: (0, 1) is a
    neighbor-tone bounce, (0, 2) an arpeggio lift, (0, -1) a lean downward."""
    out = []
    for (b, note, ln) in phrase:
        if note is None or ln < min_len:
            out.append((b, note, ln))
            continue
        steps = int(round(ln / 0.5))
        for k in range(steps):
            out.append((b + k * 0.5,
                        step_in_mode(note, shape[k % len(shape)]), 0.5))
    return out


def bounce(line):
    """A NES bassline does not sit on a root — it bounces root/octave, which is
    most of why the console's low end sounds like it is running rather than
    standing. Returns twice as many notes at half the length."""
    out = []
    for note in line:
        up = note[0] + (note[1] if note[1] in "#b" else "") + str(int(note[-1]) + 1)
        out.extend([note, up])
    return out


def transpose(note, semis):
    if note is None or semis == 0:
        return note
    f = hz(note) * (2.0 ** (semis / 12.0))
    # Back to the nearest named note, sharps only.
    n = int(round(12 * np.log2(f / 440.0))) + 9 + 48
    names = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
    return names[n % 12] + str(n // 12)


## One four-bar slot. `phrase` is "A" or "B"; everything else is voicing.
## THE MENU'S ANSWERING FIGURE — three notes that reply to the tune in its own
## sustains. It is the one piece of melodic material in the whole set that
## belongs to a single track, and it is what stops the title screen from being
## the clubhouse at a slightly different tempo.
ANSWER_A = [(6.5, "D5", 0.5), (7.0, "E5", 0.5), (7.5, "F5", 0.5),
            (14.5, "A4", 0.5), (15.0, "C5", 0.5), (15.5, "D5", 0.5)]
ANSWER_B = [(6.5, "C5", 0.5), (7.0, "D5", 0.5), (7.5, "E5", 0.5),
            (14.5, "F4", 0.5), (15.0, "G4", 0.5), (15.5, "A4", 0.5)]


def Slot(phrase, duty=0.5, gain=0.20, oct_=0, counter=None, arp=False,
         bass_sub=1.0, lift=False, bass_gain=0.28, busy_shape=None,
         bass_bounce=False, bass_walk=False, double=None, stac=None,
         answer=None, ficta_=False):
    """`bass_walk`, `double`, `stac` and `answer` all exist for one reason:
    three tracks had come out as the same arrangement at three tempos.

    `busy_shape` + `bass_bounce` + a 50 % duty + a full kit was the ONLY way to
    write a bright track here, so every bright track was written that way and
    they measured 0.90+ against each other. These are the other ways."""
    return dict(phrase=phrase, duty=duty, gain=gain, oct=oct_, counter=counter,
                arp=arp, bass_sub=bass_sub, lift=lift, bass_gain=bass_gain,
                busy_shape=busy_shape, bass_bounce=bass_bounce,
                bass_walk=bass_walk, double=double, stac=stac, answer=answer,
                ficta=ficta_)


## THE HIGHEST NOTE ANY ARRANGEMENT MAY WRITE.
##
## Pete: *"Theres some high pitched parts in the menu song that cringe my ear."*
## Counted off the score rather than guessed at from a spectrum, the menu wrote
## **34 of its 291 notes above A5 — 12 %, the highest proportion in the set** —
## and reached A6 repeatedly. Not because anybody chose A6, but because an
## octave shift, a busy pass and a counter-line each moved a note up a little and
## nothing was watching the total.
##
## So there is a ceiling, and anything over it drops an octave rather than being
## refused: a melody that wants to rise should still rise, it just does it in a
## register a person can sit with for ten minutes. C6 is the top of a comfortable
## soprano and about where a 50 % square stops being bright and starts being
## piercing.
NOTE_PC = {n: i for i, n in enumerate(
    ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"])}

CEILING = "C6"


def capped(note):
    if note is None:
        return None
    top = hz(CEILING)
    while note is not None and hz(note) > top:
        note = transpose(note, -12)
    return note


def lay_form(song, form, start=0.0, arp_gain=0.15, arp_rate=60.0, arp_duty=0.25):
    """Write a whole arrangement. Returns the beat it ends on, which is what the
    caller uses to size the song — so the form and the length cannot drift."""
    at = start
    for slot in form:
        base_phrase = PHRASE_A if slot["phrase"] == "A" else PHRASE_B
        ## Ficta first, so the counter-line inherits it. The counter reads
        ## `base_phrase`, and a harmony that kept the F natural against a
        ## sharpened melody is a semitone clash, not a harmony.
        if slot["ficta"]:
            base_phrase = ficta(base_phrase)
        phrase = base_phrase
        if slot["busy_shape"] is not None:
            phrase = busy(phrase, shape=slot["busy_shape"])
        bassline = BASS_A if slot["phrase"] == "A" else BASS_B
        if slot["bass_bounce"]:
            bassline = bounce(bassline)
        elif slot["bass_walk"]:
            bassline = walk(bassline)
        prog = PROG_A if slot["phrase"] == "A" else PROG_B
        lift = slot["lift"]

        stac = slot["stac"]
        for (b, note, ln) in phrase:
            if note is None:
                continue
            n2 = capped(transpose(major_lift(note) if lift else note, slot["oct"] * 12))
            ln2 = ln * stac if stac else ln
            song.lead(at + b, n2, ln2, duty=slot["duty"], gain=slot["gain"])
            ## An octave double is weight without brightness — the same note
            ## underneath, never above, so it cannot push anything toward the
            ## ceiling. It is what lets the menu state the tune plainly and
            ## still sound like the biggest thing in the set.
            if slot["double"] is not None:
                song.lead(at + b, capped(transpose(n2, int(slot["double"]))), ln2,
                          duty=slot["duty"], gain=slot["gain"] * 0.45, chan="p2")

        ## CALL AND RESPONSE. The answer lands in the tune's own sustains
        ## instead of underneath it, which is a different thing from a counter
        ## line and belongs to exactly one track.
        for (b, note, ln) in (slot["answer"] or []):
            song.lead(at + b, capped(note), ln, duty=0.5, gain=0.135, chan="p2")

        ## The counter-line is what keeps a repeated phrase from being a repeat.
        ## THE COUNTER IS TAKEN FROM THE ORIGINAL PHRASE, NOT THE BUSIED ONE.
        ##
        ## It used to read whatever `phrase` had become, so on a slot with both
        ## `busy_shape=(0, 2)` and a counter a fifth above, the two lifts
        ## COMPOUNDED: a G5 in the melody became B5 through the busy pass and
        ## then F#6 in the harmony. Nobody wrote "put a note at F#6" — it fell
        ## out of two reasonable decisions multiplying.
        c = slot["counter"]
        if c is not None:
            for (b, note, ln) in base_phrase:
                if note is None:
                    continue
                n2 = capped(transpose(major_lift(note) if lift else note, int(c["semis"])))
                song.lead(at + b, n2, ln, duty=c.get("duty", 0.125),
                          gain=c.get("gain", 0.07), chan="p2",
                          vib=c.get("vib", False))

        sub = slot["bass_sub"]
        steps = int(round(1.0 / sub))
        per = 16.0 / len(bassline)          ## a bounced line is twice as long
        for i, note in enumerate(bassline):
            n2 = transpose(major_lift(note) if lift else note, 0)
            for k in range(steps):
                song.bass(at + i * per + k * sub * per, n2, sub * per,
                          gain=slot["bass_gain"] * (1.0 if k == 0 else 0.62))

        if slot["arp"]:
            for i, ch in enumerate(prog):
                notes = CHORD[ch]
                if lift and ch in ("D", "F"):
                    notes = CHORD["D"]
                ## Root and fifth only. The octave on top was the third voice in
                ## a stack of squares and it is the one that turns weight into
                ## clutter — a guitar power chord is two notes for the same
                ## reason.
                song.chord(at + i, notes[:2], 1.0, duty=arp_duty, gain=arp_gain)
        at += 16.0
    return at


def sized(bpm, form, tail_beats=0.0, swing=0.0):
    """A song exactly as long as its form. The length is DERIVED, which is the
    whole fix: there is no second number to get wrong."""
    beats = len(form) * 16.0 + tail_beats
    return Song(bpm, int(round(beats / 4.0)), swing=swing)


