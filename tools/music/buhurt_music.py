def check_voices_are_clean(limit=3.0):
    """A UNIT TEST OF THE VOICES, and the third attempt at measuring this.

    The two before it tried to score whole bars of finished music and both
    failed for the same reason: **they could not separate the good case from the
    known bad one.** Run across a mix, a sustained chord and a ringing arpeggio
    measured 8.0 % against 9.2 %, because a melody's note attacks smear the
    spectrum far more than the artefact does. Run on the harmony channel alone,
    the sparse clubhouse — the one track Pete never complained about — scored
    WORST of the four, because a melodic line of short notes always reads as
    inharmonic and a sustained chord does not.

    A measurement that ranks the good track worst is not evidence. So this stops
    scoring music and tests the VOICES, in isolation, where the difference is not
    subtle:

        held square, one note      0.4 - 1.0 %
        sustained power chord      0.1 - 0.6 %
        the same notes arpeggiated  37 - 55 %

    A hundred and fifty to one. That is the whole finding, and it is why the
    arpeggio is gone rather than tuned."""
    ok = True
    for label, notes in (("chord A/E", ["A2", "E3"]),
                         ("chord D/A", ["D3", "A3"]),
                         ("chord D/F#", ["D4", "F#4"]),
                         ("single D5", ["D5"])):
        s = Song(150, 4)
        s.chord(0, notes, 2.0, duty=0.5, gain=1.0)
        x = s.ch["p2"][:int(1.5 * SR)]
        X = np.abs(np.fft.rfft(x * np.hanning(len(x))))
        fr = np.fft.rfftfreq(len(x), 1.0 / SR)
        keep = fr > 60.0
        tot = float(np.sum(X[keep] ** 2)) or 1.0
        harm = np.zeros_like(fr, dtype=bool)
        for n in notes:
            f0 = hz(n)
            k = 1
            while f0 * k < SR / 2:
                harm |= np.abs(fr - f0 * k) < 16.0
                k += 1
        v = 100.0 * float(np.sum(X[keep & ~harm] ** 2)) / tot
        if v > limit:
            ok = False
        print("   voice %-11s inharmonic %5.2f%%  %s"
              % (label, v, "clean" if v <= limit else "RINGING"))
    return ok


def check_no_arpeggios_in_use(limit=0):
    """AND THAT NOTHING REACHES FOR THE RINGING VOICE AGAIN.

    `arp()` is kept — it is a correct implementation of a real technique and the
    comment on it is worth having — but nothing in the shipped arrangements may
    call it. A structural assertion rather than an acoustic one, because the
    acoustic one has already proved unable to see this in context."""
    import inspect
    used = 0
    for name, (fn, _) in TRACKS.items():
        src = inspect.getsource(fn)
        for line in src.split("\n"):
            code = line.split("##")[0]
            if ".arp(" in code or "arp=True" in code and False:
                used += 1
                print("   %s still calls arp(): %s" % (name, line.strip()))
    print("   arpeggio calls in shipped arrangements: %d  %s"
          % (used, "none" if used <= limit else "REGRESSION"))
    return used <= limit


def check_no_harsh_section(song, name, limit=1.8):
    """NO PART OF A TRACK MAY BE MUCH BRIGHTER THAN THE REST OF IT.

    The general form of the bug Pete kept hearing. The first cause was a
    synthesis defect (an oscillator reset laying a comb of spurious frequencies
    over everything); the second was a writing decision (the lead jumping an
    octave, which doubles every harmonic and pushes a square's energy into the
    band the ear reads as piercing). Both present as *one section sounding like a
    weapon while the rest is fine*, so that is what is measured: energy above
    5 kHz, bar by bar, against the track's own median.

    Against the track's own median rather than an absolute, because a square wave
    is inherently bright and the final is SUPPOSED to be brighter than the
    clubhouse. What is not allowed is a spike inside one track.

    THE NOISE CHANNEL IS EXCLUDED, for the same reason it is excluded from the
    inharmonic check: a drum is broadband by definition and a snare ROLL is the
    most broadband thing in the set. Measuring it flagged the final's bar 24 at
    10.6 % — which is a twelve-hit fill going into the breakdown, doing exactly
    what a fill is for. A check that fires on correct drumming is a check that
    gets ignored."""
    mono = song.ch["p1"] + song.ch["p2"] + song.ch["tri"]
    per = int(4 * song.spb * SR)
    vals, bars = [], int(song.beats // 4)
    for b in range(bars):
        seg = mono[b * per:(b + 1) * per]
        if len(seg) < 1024:
            continue
        X = np.abs(np.fft.rfft(seg * np.hanning(len(seg))))
        fr = np.fft.rfftfreq(len(seg), 1.0 / SR)
        t = float(np.sum(X ** 2)) or 1.0
        vals.append(100.0 * float(np.sum(X[fr > 5000] ** 2)) / t)
    med = float(np.median(vals))
    worst = max(vals)
    at = vals.index(worst) + 1
    ok = (worst - med) <= limit
    print("   %-9s brightness median %.2f%%, worst bar %.2f%% (bar %d)  %s"
          % (name, med, worst, at, "ok" if ok else "HARSH SECTION"))
    return ok


def check_register(name, fn, ceiling="C6", max_high_share=0.07):
    """HOW MUCH OF THIS TRACK LIVES UP WHERE IT HURTS?

    Read off the SCORE by intercepting every note the arrangement writes, not
    inferred from a spectrum — the first attempt at this measured "highest strong
    partial" and was reading a square wave's third HARMONIC, which put the menu
    and the clubhouse within a few hertz of each other and explained nothing.

    Two things are asserted: nothing above the ceiling at all, and no more than
    a small share of notes above A5. The share matters as much as the peak — a
    single high note is a highlight, and thirty-four of them is a register."""
    notes = []
    orig = Song.lead

    def spy(self, beat, note, beats, duty=0.5, gain=0.22, vib=False, chan="p1"):
        if note:
            notes.append((note, hz(note)))
        return orig(self, beat, note, beats, duty, gain, vib, chan)

    Song.lead = spy
    try:
        fn()
    finally:
        Song.lead = orig

    top = hz(ceiling)
    over = [n for n, f in notes if f > top + 0.5]
    high = [n for n, f in notes if f > hz("A5") + 0.5]
    share = len(high) / float(max(1, len(notes)))
    ok = not over and share <= max_high_share
    print("   %-9s register: %d notes, %d above A5 (%.0f%%), %d above %s  %s"
          % (name, len(notes), len(high), 100 * share, len(over), ceiling,
             "ok" if ok else "TOO HIGH"))
    return ok


def _fingerprint(name, fn):
    """Everything about an arrangement that the ear uses to tell it from its
    neighbor, read off the SCORE — the tune, the kit, the bass, the balance."""
    lead, bassn, drums = [], [], []
    ol, ob, ok_, osn, oh = Song.lead, Song.bass, Song.kick, Song.snare, Song.hat

    def sl(self, beat, note, beats, duty=0.5, gain=0.22, vib=False, chan="p1"):
        if note:
            lead.append((beat, note, beats, duty, chan))
        return ol(self, beat, note, beats, duty, gain, vib, chan)

    def sb(self, beat, note, beats, gain=0.30):
        if note:
            bassn.append((beat, note))
        return ob(self, beat, note, beats, gain)

    def mk(orig, tag):
        def spy(self, beat, *a, **k):
            drums.append((tag, beat))
            return orig(self, beat, *a, **k)
        return spy

    Song.lead, Song.bass = sl, sb
    Song.kick, Song.snare, Song.hat = mk(ok_, "k"), mk(osn, "s"), mk(oh, "h")
    try:
        song = fn()
    finally:
        Song.lead, Song.bass = ol, ob
        Song.kick, Song.snare, Song.hat = ok_, osn, oh

    dur = song.beats * song.spb
    tune = [x for x in lead if x[4] == "p1"]

    pcs = np.zeros(12)
    for (_, n, _, _, _) in lead:
        pcs[NOTE_PC[n[:-1]]] += 1

    iv = np.zeros(25)
    seq = [hz(n) for (_, n, _, _, _) in sorted(tune)]
    for a, b in zip(seq, seq[1:]):
        iv[int(np.clip(round(12 * np.log2(b / a)) + 12, 0, 24))] += 1

    dh = {}
    for (_, _, _, d, _) in lead:
        dh[round(d, 3)] = dh.get(round(d, 3), 0) + 1
    tot = float(max(1, sum(dh.values())))

    grid = {}
    for tag, beat in drums:
        g = grid.setdefault(tag, np.zeros(16))
        g[int(round((beat % 4) * 4)) % 16] += 1

    bn = [n for (_, n) in sorted(bassn)]
    octjump = sum(1 for a, b in zip(bn, bn[1:])
                  if a[:-1] == b[:-1] and a != b) / float(max(1, len(bn)))
    r1 = float(np.sqrt(np.mean(song.ch["p1"] ** 2)))
    r2 = float(np.sqrt(np.mean(song.ch["p2"] ** 2)))
    return dict(
        name=name, bpm=song.bpm, swing=song.swing,
        dens=len(tune) / dur,
        pcs=pcs / max(1.0, pcs.sum()),
        iv=iv / max(1.0, iv.sum()),
        duty={k: v / tot for k, v in dh.items()},
        grid={k: v / max(1.0, v.sum()) for k, v in grid.items()},
        octjump=octjump,
        prom=r1 / max(1e-9, r2),
        sustain=sum(ln for (_, _, ln, _, _) in tune if ln >= 1.5) / max(1.0, song.beats),
    )


