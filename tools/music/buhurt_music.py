def champion(bpm=152):
    """THE CHAMPION FANFARE.

    CLEANED UP, same complaint as the final. The held notes were the most
    exposed place in the set for the vibrato — a single sustained pulse wobbling
    against a fanfare is the one thing that cannot hide — and its arpeggios were
    running at 31 Hz, which is a trill, not a chord. Both fixed at source.

    What is left is deliberately simple: rising fifths, the melody LIFTED OUT OF
    DORIAN INTO MAJOR (every F becomes F#, every C becomes C#), and a held major
    chord at the end. A victory cue should be clear, short, and over.

    The counter-lines went with the warble. At this register they were adding
    thickness where the tune wanted air."""
    form = [
        Slot("A", duty=0.5, gain=0.24, lift=True, arp=True, bass_bounce=True),
        Slot("B", duty=0.5, gain=0.24, lift=True, arp=True, bass_bounce=True),
        ## Also had the lead an octave up, and at 6.2% high-frequency share
        ## against the fanfare's 2.0% it was the single harshest moment in the
        ## set. The movement stays; the register comes back down.
        Slot("A", duty=0.5, gain=0.25, lift=True, arp=True,
             busy_shape=(0, 2), bass_bounce=True,
             counter={"semis": 7, "gain": 0.07, "duty": 0.5}),
        Slot("B", duty=0.5, gain=0.25, lift=True, arp=True, bass_bounce=True),
    ]
    s = sized(bpm, form, tail_beats=8.0)
    for i, note in enumerate(["D4", "A4", "D5", "F#5"]):
        s.lead(i * 0.5, note, 0.5, duty=0.5, gain=0.26)
        s.bass(i * 0.5, "D2", 0.5, gain=0.30)
    s.lead(2.0, "A5", 2.0, duty=0.5, gain=0.28)
    s.chord(2.0, CHORD["D"][:2], 2.0, duty=0.5, gain=0.13)
    s.bass(2.0, "D2", 2.0, gain=0.30)

    end = lay_form(s, form, start=4.0, arp_gain=0.08, arp_rate=48.0, arp_duty=0.5)
    ## The last chord is an ARPEGGIO, not three sustained pulses stacked on two
    ## channels. Three held squares beat against each other; one arpeggio is a
    ## chord, and it is how the console would have done it anyway.
    s.lead(end, "D5", 4.0, duty=0.5, gain=0.20)
    ## The last chord is held, not cycled. A fanfare's final chord is the
    ## most exposed sound in the whole set — it is alone, it is long, and it is
    ## what the player remembers. Arpeggiating it put fifty per cent inharmonic
    ## energy on the one note that had nowhere to hide.
    s.chord(end, ["D4", "F#4", "A4"], 4.0, duty=0.5, gain=0.15)
    s.bass(end, "D2", 4.0, gain=0.30)

    for bar in range(int(s.beats // 4)):
        base = bar * 4
        if bar < 1:
            continue
        s.kick(base, 0.34)
        s.kick(base + 2, 0.30)
        s.snare(base + 1, 0.22)
        s.snare(base + 3, 0.22)
        for e in (0.5, 1.5, 2.5, 3.5):
            s.hat(base + e, 0.06)
    ramp(s, "noi", 4.0, 0.0)
    return s


