def final(bpm=172):
    """THE FINAL — its own song. See THE BOSS THEME above for why.

    Written as a riff piece rather than through the form system, because the
    form system exists to arrange a MELODY across slots and this is not that: it
    is one ostinato that never stops, with things happening over it. Forcing it
    through `lay_form` would have produced a third arrangement of the club theme
    wearing a different hat, which is precisely what Pete rejected.

    Structure, and it is a shape rather than a repeat:

        bars  1-4    the riff alone, with the drums. Nothing else.
        bars  5-12   the lead arrives over it
        bars 13-20   the climb — the half that goes somewhere
        bars 21-24   riff and power chords, no lead. The breakdown.
        bars 25-32   everything

    The riff is on the triangle AND doubled by a low pulse, which is how a NES
    gets a bass part to sound like a rhythm guitar."""
    BARS = 32
    s = Song(bpm, BARS)

    def riff_at(bar, lead_gain=0.0, duty=0.25):
        base = bar * 4.0
        for (b, note, ln) in RIFF:
            s.bass(base + b, note, ln, gain=0.30)
            if lead_gain > 0.0:
                s.lead(base + b, note, ln, duty=duty, gain=lead_gain)

    def line_at(bar, phrase, gain=0.21, duty=0.25, oct_=0):
        base = bar * 4.0
        for (b, note, ln) in phrase:
            s.lead(base + b, transpose(note, oct_ * 12), ln,
                   duty=duty, gain=gain, chan="p1")

    def chords_at(bar, gain=0.105):
        base = bar * 4.0
        for i, ch in enumerate(BOSS_PROG):
            s.chord(base + i, CHORD[ch][:2], 1.0, duty=0.34, gain=gain)

    ## Every two bars is one turn of the riff, all thirty-two bars of it.
    for bar in range(0, BARS, 2):
        ## Bars 1-4 carry the riff on the pulse as well, so the opening has
        ## weight before the lead exists to give it any.
        riff_at(bar, lead_gain=0.13 if bar < 4 else 0.075)

    for bar in range(4, 12, 2):
        line_at(bar, BOSS_A)
        if bar >= 8:
            chords_at(bar)
    for bar in range(12, 20, 2):
        line_at(bar, BOSS_B, gain=0.22)
        chords_at(bar)
    for bar in range(20, 24, 2):
        ## THE BREAKDOWN. No lead at all — riff, chords and drums. The check that
        ## refuses a track with a hole in it passes because the riff is a tune,
        ## which is the difference between a breakdown and the bug in pass one.
        chords_at(bar, gain=0.14)
    for bar in range(24, 32, 2):
        line_at(bar, BOSS_A if bar < 28 else BOSS_B, gain=0.23)
        chords_at(bar, gain=0.115)

    for bar in range(BARS):
        base = bar * 4
        s.kick(base, 0.34)
        s.kick(base + 2, 0.30)
        for beat in range(4):
            s.war(base + beat, 0.30 if beat % 2 == 0 else 0.20)
            s.hat(base + beat + 0.5, 0.045)
        s.snare(base + 1, 0.24)
        s.snare(base + 3, 0.24)
        ## A roll into each eight-bar section, and a longer one into the last.
        if bar % 8 == 7:
            n = 12 if bar == 23 else 8
            for k in range(n):
                s.snare(base + 4.0 - n * 0.25 + k * 0.25, 0.10 + k * 0.028, period=2)
    return s


