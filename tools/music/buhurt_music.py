def _cos(a, b):
    d = float(np.linalg.norm(a) * np.linalg.norm(b))
    return float(a @ b / d) if d else 0.0


def _twin_score(a, b):
    ks = set(a["grid"]) | set(b["grid"])
    z = np.zeros(16)
    drums = float(np.mean([_cos(a["grid"].get(k, z), b["grid"].get(k, z))
                           for k in ks])) if ks else 0.0
    dk = set(a["duty"]) | set(b["duty"])
    parts = dict(
        melody=_cos(a["iv"], b["iv"]),
        mode=_cos(a["pcs"], b["pcs"]),
        drums=drums,
        duty=sum(min(a["duty"].get(k, 0.0), b["duty"].get(k, 0.0)) for k in dk),
        tempo=1.0 - min(1.0, abs(a["bpm"] - b["bpm"]) / 40.0),
        dens=1.0 - min(1.0, abs(a["dens"] - b["dens"]) / 3.0),
        bass=1.0 - min(1.0, abs(a["octjump"] - b["octjump"])),
        prom=1.0 - min(1.0, abs(np.log2(max(a["prom"], 1e-6))
                                - np.log2(max(b["prom"], 1e-6))) / 2.5),
        sustain=1.0 - min(1.0, abs(a["sustain"] - b["sustain"]) / 0.5),
        swing=1.0 - min(1.0, abs(a["swing"] - b["swing"]) / 0.08),
    )
    return sum(_TWIN_W[k] * parts[k] for k in _TWIN_W) / sum(_TWIN_W.values()), parts


def check_no_two_tracks_are_twins(gate=TWIN_GATE):
    """NO TWO TRACKS MAY BE THE SAME ARRANGEMENT AT DIFFERENT TEMPOS.

    Three times now the same failure: the final was cup night sped up, the menu
    borrowed Worlds' drone, and then the menu, the clubhouse and your own
    tournament came out as ONE arrangement at 118 / 124 / 132 — measuring 0.92,
    0.97 and 0.90 against each other. Every time, Pete heard it and no check
    did, because every check in this file looks at ONE track.

    The register already had the rule written down — *a signature belongs to one
    track* — and a rule in a document is not a gate. This is the gate.

    It reads the score, not the audio, and it prints the whole matrix every
    build so a pair drifting together is visible before it is audible."""
    names = list(TRACKS.keys())
    F = {n: _fingerprint(n, TRACKS[n][0]) for n in names}

    worst, pairs = 0.0, []
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            v, parts = _twin_score(F[a], F[b])
            pairs.append((v, a, b, parts))
            worst = max(worst, v)
    pairs.sort(reverse=True, key=lambda x: x[0])

    ## THE POSITIVE CONTROL. A check that cannot separate the good case from the
    ## known bad case is not evidence — so the bad case is manufactured here,
    ## every run, rather than assumed.
    twin, _ = _twin_score(F["club"], _fingerprint("club'", lambda: club(bpm=132)))
    blind = twin <= gate

    over = [p for p in pairs if p[0] > gate]
    ok = not over and not blind

    print("   twins     worst pair %s/%s %.2f (gate %.2f), control twin %.2f  %s"
          % (pairs[0][1], pairs[0][2], pairs[0][0], gate, twin,
             "BLIND — the control twin scored under the gate" if blind
             else ("ok" if ok else "TOO ALIKE")))
    for v, a, b, parts in pairs[:3]:
        print("             %-9s %-9s %.2f  " % (a, b, v)
              + " ".join("%s %.2f" % (k, parts[k]) for k in
                         ("melody", "drums", "duty", "dens", "bass", "prom", "swing")))
    for v, a, b, _ in over:
        print("             TOO ALIKE: %s and %s at %.2f" % (a, b, v))
    return ok


def check_holes(song, name, max_quiet_bars=1):
    """NO BAR OF A TRACK MAY BE DRUMS ONLY.

    This is the check that would have caught the thing Pete heard. It measures
    tonal energy — both pulses plus the triangle — bar by bar, and fails on any
    run of bars with none. `max_quiet_bars` is 1 because a single bar of drums is
    a fill and twenty-four of them is a bug."""
    per = int(4 * song.spb * SR)
    bars = int(song.beats // 4)
    tonal = np.abs(song.ch["p1"]) + np.abs(song.ch["p2"]) + np.abs(song.ch["tri"])
    quiet, worst, run = [], 0, 0
    for b in range(bars):
        seg = tonal[b * per:(b + 1) * per]
        if len(seg) == 0 or float(np.max(seg)) < 1e-3:
            quiet.append(b + 1)
            run += 1
            worst = max(worst, run)
        else:
            run = 0
    ok = worst <= max_quiet_bars
    print("   %-9s %2d bars, %d with no tune (longest run %d)  %s"
          % (name, bars, len(quiet), worst, "ok" if ok else "HOLE: bars " + str(quiet)))
    return ok


