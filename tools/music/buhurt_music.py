#!/usr/bin/env python3
"""
Retro Buhurt — the music set.  One melody, arranged four ways.

WHY THIS IS A SYNTHESISER AND NOT A SOUNDFONT
---------------------------------------------
The event-music recipe renders MIDI through FluidR3_GM, which is right for the
acoustic and metal sets it was written for.  It is wrong here.  Pete asked for
Retro Bowl's idiom with medieval flavour, escalating to "8-bit war drum and
8-bit metal" — and *8-bit* is not a texture you can approximate with a General
MIDI patch.  It is four specific voices:

    PULSE 1/2   square waves at 12.5 / 25 / 50 % duty.  Leads and harmony.
    TRIANGLE    a stepped triangle.  The NES bass, and it cannot be silenced
                cleanly, which is why NES basslines run constantly.
    NOISE       a pseudo-random bit generator.  Every drum on the console.

So those four are written directly.  "8-bit metal" then stops being a metaphor
and becomes the actual technique: a distorted power chord is faked on the NES by
ARPEGGIATING the chord faster than the ear separates it — root, fifth, octave at
60 Hz — which is what makes Mega Man and Castlevania sound like guitars.  And
"war drums" are the noise channel at a long period, doubled by a pitch-dropped
triangle thump, which is how every NES boss room in history got its kick.

THE MUSIC
---------
Retro Bowl's theme is HeatleyBros' "8 Bit Joy" (2017) — bright, major-key,
perky NES.  We are not copying it; we are writing in that idiom and bending it,
which is exactly what Pete asked for.

The bend is MODE.  HeatleyBros is Ionian (plain major).  Medieval music is
modal, and the mode that reads as "medieval" to a modern ear is DORIAN — a minor
scale with a raised sixth, which is why every folk tune about a battle sounds
the way it does.  So the melody is in D Dorian and keeps the perky NES rhythm:
the pulse and the phrasing say arcade, the mode says 1350.

ONE MELODY, FOUR ARRANGEMENTS — Pete's plan, and the whole reason the boss idea
works.  You recognise the tune and the room has changed around it:

    club       112 BPM, Dorian.  Triangle and one soft pulse.  Sparse.
    cup        140 BPM, Dorian.  War drums enter.  Both pulses.
    final      168 BPM, Dorian.  Arpeggiated power chords, double-time war
               drums, 12.5 % duty lead.  8-bit metal.
    champion   150 BPM, and the tune lifts out of Dorian into MAJOR — F natural
               becomes F sharp.  A fanfare that is the same melody you have been
               hearing all game, finally in the bright mode.  That lift is the
               oldest trick in game music and it still works.
"""

import numpy as np
import wave, os, sys

SR = 44100

# --------------------------------------------------------------- the console
# Equal temperament, A4 = 440.  Note names as "D4", "F#3", or None for a rest.
_STEP = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def hz(note):
    if note is None:
        return 0.0
    name = note[0].upper()
    i = 1
    semis = _STEP[name]
    while i < len(note) and note[i] in "#b":
        semis += 1 if note[i] == "#" else -1
        i += 1
    octave = int(note[i:])
    return 440.0 * (2.0 ** ((semis + (octave - 4) * 12 - 9) / 12.0))


def pulse(freq, n, duty=0.5, detune=0.0):
    """A square wave with a duty cycle.  12.5 % is thin and buzzy (the classic
    NES lead), 50 % is fat and hollow.  Phase-accumulated rather than computed
    from t, so a frequency that changes mid-note does not click."""
    if freq <= 0:
        return np.zeros(n, dtype=np.float32)
    f = np.full(n, freq * (1.0 + detune), dtype=np.float64)
    phase = np.cumsum(f) / SR
    return np.where((phase % 1.0) < duty, 1.0, -1.0).astype(np.float32)


def triangle(freq, n, steps=16):
    """The NES triangle is STEPPED — 16 levels — which is why it sounds slightly
    gritty rather than pure.  Quantising it is the difference between a bass that
    sounds like a console and one that sounds like a sine."""
    if freq <= 0:
        return np.zeros(n, dtype=np.float32)
    phase = (np.arange(n) * freq / SR) % 1.0
    tri = 2.0 * np.abs(2.0 * (phase - np.floor(phase + 0.5))) - 1.0
    return (np.round(tri * (steps / 2)) / (steps / 2)).astype(np.float32)


def noise(n, period=1, seed=0):
    """A 15-bit LFSR, the same shape the 2A03 uses.  A short period is a hiss
    (hats), a long one is a rumble (war drums).  Generated by holding a random
    value for `period` samples rather than filtering white noise, because the
    holding is what gives it the metallic pitch the console has."""
    rng = np.random.default_rng(seed)
    hold = max(1, int(period))
    raw = rng.integers(0, 2, size=(n // hold) + 1).astype(np.float32) * 2.0 - 1.0
    return np.repeat(raw, hold)[:n]


def env(n, attack=0.002, decay=0.0, sustain=1.0, release=0.05):
    """A NES envelope is a handful of volume steps, so this is deliberately
    blunt.  Release matters most: without it every note ends in a click."""
    e = np.ones(n, dtype=np.float32) * sustain
    a = min(int(attack * SR), n)
    if a > 0:
        e[:a] = np.linspace(0.0, 1.0, a)
    if decay > 0:
        d = min(int(decay * SR), n - a)
        if d > 0:
            e[a:a + d] = np.linspace(1.0, sustain, d)
    r = min(int(release * SR), n)
    if r > 0:
        e[-r:] *= np.linspace(1.0, 0.0, r)
    return e


def vibrato(freq, n, depth=0.0028, rate=5.0, delay=0.22):
    """Pitch wobble that starts LATE and shallow.  A vibrato present from the
    attack sounds like a broken oscillator; one that arrives a fifth of a second
    in sounds like a player.  Depth more than halved after the first pass — at
    0.6 % it was audible as pitch instability rather than as expression."""
    t = np.arange(n) / SR
    on = np.clip((t - delay) * 6.0, 0.0, 1.0)
    return freq * (1.0 + depth * on * np.sin(2 * np.pi * rate * t))


# ------------------------------------------------------------------ the score
class Song:
    """A fixed-length buffer per channel.  Everything is written by absolute
    beat, so an arrangement is a list of what happens rather than a sequence to
    step through — which is what lets four arrangements share one melody."""

    def __init__(self, bpm, bars, beats_per_bar=4, swing=0.0):
        self.bpm = bpm
        self.spb = 60.0 / bpm
        ## SWING BELONGS TO ONE TRACK. `hosted` is the only celebration in the
        ## game and it is the only thing here that swings — every off-eighth is
        ## pushed late by this fraction of a beat, which is the single cheapest
        ## way to make an arrangement unmistakable for its neighbors. Applied
        ## on the clock rather than in the writing, so the drums, the bass and
        ## the tune all lean together instead of one of them sitting square.
        self.swing = swing
        self.beats = bars * beats_per_bar
        self.n = int(self.beats * self.spb * SR) + SR // 2
        self.ch = {k: np.zeros(self.n, dtype=np.float32)
                   for k in ("p1", "p2", "tri", "noi")}

    def at(self, beat):
        if self.swing:
            f = beat % 1.0
            if abs(f - 0.5) < 1e-6:
                beat += self.swing
        return int(beat * self.spb * SR)

    def add(self, chan, beat, buf, gain=1.0):
        i = self.at(beat)
        j = min(self.n, i + len(buf))
        if j > i:
            self.ch[chan][i:j] += buf[:j - i] * gain

    # -- voices -----------------------------------------------------------
    def lead(self, beat, note, beats, duty=0.5, gain=0.22, vib=False, chan="p1"):
        """VIBRATO IS OFF BY DEFAULT, and that is the fix for the warble.

        It used to be on for every lead note in every track. On a sparse
        clubhouse loop that is a nice touch; on the final — where the lead is
        12.5 % duty, doubled an octave down, over arpeggios — five wobbling
        oscillators at slightly different rates is a mess, and Pete called it
        exactly: *"too chaotic, especially with that warble sound in there."*
        Held notes in the champion fanfare were the same thing, exposed.

        Real NES vibrato is applied by hand, to long notes, sparingly. So it is
        opt-in now, shallower, and `long_notes_only` below is what actually uses
        it."""
        if note is None:
            return
        n = max(1, int(beats * self.spb * SR))
        f = hz(note)
        wave_ = self._fm_pulse(f, n, duty) if vib else pulse(f, n, duty)
        self.add(chan, beat, wave_ * env(n, 0.004, 0.05, 0.85, min(0.06, beats * self.spb * 0.4)), gain)

    def _fm_pulse(self, f, n, duty):
        ph = np.cumsum(vibrato(f, n)) / SR
        return np.where((ph % 1.0) < duty, 1.0, -1.0).astype(np.float32)

    def bass(self, beat, note, beats, gain=0.30):
        if note is None:
            return
        n = max(1, int(beats * self.spb * SR))
        self.add("tri", beat, triangle(hz(note), n) * env(n, 0.002, 0.0, 1.0, 0.03), gain)

    def arp(self, beat, notes, beats, rate_hz=60.0, duty=0.25, gain=0.16, chan="p2"):
        """8-BIT METAL, and it is not an effect — it is the technique.  A NES
        cannot hold a chord on one channel, so a power chord is faked by cycling
        root/fifth/octave faster than the ear separates them, and it reads as one
        buzzing, distorted note.  Precisely how Mega Man and Castlevania sound
        like electric guitars.

        THE RATE IS IN HERTZ, NOT BEATS, and that is the second half of the
        warble fix.  A real NES steps the arpeggio once per video frame — 60 Hz,
        about 17 ms — which is comfortably above the rate at which the ear stops
        hearing separate notes.  Specifying it in BEATS meant the rate moved with
        the tempo and drifted into the worst possible band: the champion cue ran
        at 31 Hz and the final at 45 Hz, both too fast to be melody and too slow
        to fuse.  That is not a chord, it is a trill, and it is what Pete heard
        warbling.        THE PHASE MUST BE CONTINUOUS ACROSS THE STEPS, and getting that wrong
        is what made this sound like a weapon.

        The first version built each step by calling `pulse()` afresh, so the
        oscillator SNAPPED BACK TO PHASE ZERO sixty times a second. That edge is
        not part of any of the three notes — it is an impulse train at the step
        rate, and an impulse train has energy at every harmonic of itself all the
        way up through the audible range. Pete, twice: *"that warble sound"*, and
        then *"a gun ray of sound into my ears."* He was describing a 60 Hz buzz
        with a full harmonic stack on it, because that is precisely what it was.

        Measured: 50 ms of arpeggio contained an extra discontinuity every 16.7
        ms that no waveform in it accounted for.

        A real NES has no such artefact, and not because it is careful — the
        channel simply keeps oscillating and only its PERIOD register changes.
        So the frequency is built as an array and integrated ONCE. One phase, one
        cumulative sum, no seams.
        """
        total = max(1, int(beats * self.spb * SR))
        step_n = max(48, int(SR / max(1.0, rate_hz)))
        freqs = np.empty(total, dtype=np.float64)
        pos, k = 0, 0
        while pos < total:
            m = min(step_n, total - pos)
            freqs[pos:pos + m] = hz(notes[k % len(notes)])
            pos += m
            k += 1
        phase = np.cumsum(freqs) / SR
        out = np.where((phase % 1.0) < duty, 1.0, -1.0).astype(np.float32)
        self.add(chan, beat, out * env(total, 0.003, 0.0, 1.0, 0.04), gain)

    def chord(self, beat, notes, beats, duty=0.5, gain=0.10, chan="p2",
              spread=0.0012):
        """A POWER CHORD THAT IS ACTUALLY A CHORD.

        This replaces the arpeggio, and the reason is measured rather than
        aesthetic. Cycling three pitches at 48-60 Hz does not just sound like a
        chord — it FREQUENCY-MODULATES the oscillator at 48-60 Hz, which throws
        sidebands either side of every harmonic. Those sidebands are inharmonic
        by construction:

            a held square          0.4 - 1.0 % inharmonic energy
            the same notes arped   37 - 55 %

        Fifty per cent inharmonic content is a ring modulator. Pete described it
        four separate ways — warble, chaotic, *"a gun ray of sound into my
        ears"*, still there — and every one of them was right. I kept fixing how
        the arpeggio was BUILT (the phase seam was a real bug and worth fixing)
        without questioning whether to use one at all.

        THE TECHNIQUE WAS NEVER THE REQUIREMENT. A NES arpeggiates because it has
        five voices and cannot hold a chord. We are writing 8-bit-STYLED music in
        Python with as many oscillators as we want, so the honest thing is to
        hold the notes — which is also closer to what a real power chord is. Same
        weight, same square-wave character, none of the modulation.

        `spread` detunes each voice a fraction of a percent so the stack thickens
        instead of phasing — the one trick borrowed from analogue rather than
        from the console."""
        n = max(1, int(beats * self.spb * SR))
        e = env(n, 0.006, 0.03, 0.92, min(0.05, beats * self.spb * 0.3))
        for i, note in enumerate(notes):
            f = hz(note) * (1.0 + spread * (i - (len(notes) - 1) / 2.0))
            self.add(chan, beat, pulse(f, n, duty) * e, gain / max(1.0, len(notes) ** 0.7))

    # -- percussion -------------------------------------------------------
    def kick(self, beat, gain=0.55, drop=(150.0, 45.0), dur=0.11):
        """Triangle with the pitch dropping off a cliff — the NES kick.  The
        noise channel alone gives you a click, not a thump."""
        n = int(dur * SR)
        f = np.linspace(drop[0], drop[1], n)
        ph = np.cumsum(f) / SR
        body = (2.0 * np.abs(2.0 * ((ph % 1.0) - 0.5)) - 1.0).astype(np.float32)
        self.add("tri", beat, body * env(n, 0.001, dur * 0.5, 0.25, dur * 0.4), gain)

    def snare(self, beat, gain=0.30, period=3, dur=0.09):
        n = int(dur * SR)
        self.add("noi", beat, noise(n, period, seed=int(beat * 97) & 0xFFFF)
                 * env(n, 0.001, dur * 0.6, 0.15, dur * 0.35), gain)

    def hat(self, beat, gain=0.10, dur=0.028):
        n = int(dur * SR)
        self.add("noi", beat, noise(n, 1, seed=int(beat * 31) & 0xFFFF)
                 * env(n, 0.0005, dur * 0.7, 0.1, dur * 0.25), gain)

    def war(self, beat, gain=0.42, dur=0.20):
        """THE WAR DRUM.  Long-period noise for the skin, a low triangle thump
        underneath for the body.  One without the other is a hiss or a click;
        together they are the thing at the front of a boss room."""
        n = int(dur * SR)
        self.add("noi", beat, noise(n, 9, seed=int(beat * 53) & 0xFFFF)
                 * env(n, 0.002, dur * 0.55, 0.30, dur * 0.4), gain)
        m = int(dur * 0.8 * SR)
        f = np.linspace(96.0, 58.0, m)
        ph = np.cumsum(f) / SR
        body = (2.0 * np.abs(2.0 * ((ph % 1.0) - 0.5)) - 1.0).astype(np.float32)
        self.add("tri", beat, body * env(m, 0.001, 0.05, 0.3, 0.05), gain * 0.8)

    def loop_length(self):
        """Exactly the written bars, with the half-second working pad cut off.

        A LOOP MUST END WHERE IT BEGINS. The pad exists so a note released on the
        last beat has somewhere to ring; shipping it means the file ends in
        silence and the loop dips audibly every time it comes round. Measured at
        8.5 dB on the club track before this existed."""
        return int(self.beats * self.spb * SR)

    def mix(self, levels=None, loop=True):
        lv = {"p1": 0.95, "p2": 0.80, "tri": 1.0, "noi": 0.85}
        if levels:
            lv.update(levels)
        out = sum(self.ch[k] * lv[k] for k in self.ch)
        if loop:
            out = out[:self.loop_length()]
        peak = float(np.max(np.abs(out))) or 1.0
        return (out / peak * 0.89).astype(np.float32)


def ramp(song, chan, until_beat, floor=0.55):
    """ENTRANCES ARE NEVER SUDDEN — the recipe's rule.

    USED ONLY ON THE ONE-SHOT. It is exactly wrong on a loop: a quiet first bar
    is a dip every time the loop comes round, and the entrance is already handled
    where it belongs — `Audio._begin()` starts a track at -80 dB and tweens it
    up, which can also be interrupted. Baking a second one in means fading twice
    on entry and forever afterwards."""
    i = song.at(until_beat)
    if i <= 0:
        return
    song.ch[chan][:i] *= np.linspace(floor, 1.0, i).astype(np.float32)


def write_wav(path, mono):
    st = np.stack([mono, mono], axis=1)
    pcm = np.clip(st * 32767.0, -32768, 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


