    s = sized(bpm, form)
    lay_form(s, form, arp_gain=0.085, arp_duty=0.5)

    ## THE DRONE, laid in four-bar lengths rather than one long note so the
    ## envelope re-articulates and it breathes like an instrument being played
    ## rather than a tone being held. Low gain: it is the floor, not a part.
    for bar in range(0, int(s.beats // 4), 4):
        ## Louder now that it is Worlds' alone. It was sharing the one
        ## distinctive texture in the set with the title screen, which made both
        ## weaker — so it is turned up and the menu's is gone entirely.
        s.chord(bar * 4.0, ["D2", "A2"], 16.0, duty=0.5, gain=0.115, spread=0.0016)
        s.chord(bar * 4.0, ["D3", "A3"], 16.0, duty=0.5, gain=0.055, spread=0.0020)

    for bar in range(int(s.beats // 4)):
        base = bar * 4
        ## A PROCESSIONAL, not a rock beat. The war drum lands on 1 and 3 with a
        ## pickup into the bar, which is how a march moves — the final's
        ## every-beat pattern would make this frantic, and frantic is what it is
        ## deliberately not.
        s.war(base, 0.34)
        s.war(base + 2, 0.26)
        s.war(base + 3.5, 0.18)
        s.kick(base, 0.30)
        s.snare(base + 2, 0.20)
        for e in (1.0, 3.0):
            s.hat(base + e, 0.05)
        if bar % 8 == 7:
            for k in range(6):
                s.snare(base + 2.5 + k * 0.25, 0.10 + k * 0.035, period=2)
    return s


