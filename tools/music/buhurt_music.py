def menu(bpm=129.2):
    """THE TITLE SCREEN — third version, and the second one Pete caught.

    Version one was 100 BPM and sparse, which was a regression on a correction
    he had already given me. Version two fixed the tempo and the density and in
    doing so made it **the clubhouse at 124 BPM**: same busied phrase, same
    bouncing bass, same kit, same 50 % duty. Measured against club it came out
    at 0.92, and against hosted at 0.97. He heard it before I measured it, for
    the third time in this set.

    So the menu is no longer a brighter arrangement of the clubhouse — it is a
    DIFFERENT READING of the same tune, and every lever is set the other way:

    * **The tune is played plainly, not busied.** Club's whole idea is a lead
      that never stops moving; the menu states the melody in long staccato
      notes, about a third the note rate. A title theme is the one that has to
      be singable after ten seconds.
    * **It is octave-doubled** rather than harmonised, so it is heavy without
      being bright, and nothing moves toward the ceiling.
    * **The bass walks** root-fifth-octave-fifth where club bounces.
    * **Call and response** — `ANSWER_A`/`ANSWER_B` reply in the melody's own
      sustains. Nothing else in the set does this.
    * **A march kit**: backbeat snare, kick on the one and the and-of-three, hats
      on quarters. Club's kit is eighths; hosted's swings.

    The two-beat pickup stays. It is the game announcing itself."""
